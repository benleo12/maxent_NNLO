    mtlep=sqrt(max(2.0_wp*(ptl*ptnu-pl(1)*pn(1)-pl(2)*pn(2)),0.0_wp))
    iq=0; if(qt>=25.0_wp) iq=1; if(qt>=50.0_wp) iq=2
    ia=0; if(abs(c)>0.6_wp) ia=1; if(abs(c)>=0.7_wp) ia=2
    im=0; if(mass>=76.0_wp) im=1; if(mass>=84.0_wp) im=2
