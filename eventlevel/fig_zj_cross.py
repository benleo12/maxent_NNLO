EFF_MARG, EFF_JOINT = 61.66412987550925, 35.87563906060581


def main():
    global DATA
    effA, effB = EFF_MARG, EFF_JOINT
    res = os.path.join(HERE, "zj_cross_results.npz")
    if os.path.exists(res):
        # regenerated by zj_cross_demo.py (+ sigma_FO from the seed scatter)
        R = np.load(res)
        DATA = {tuple(int(v) for v in mn): (float(fo), float(er), float(pr), float(ma), float(mi))
                for mn, fo, er, pr, ma, mi in zip(R["mn"], R["fo"], R["err"], R["prior"], R["marg"], R["mixed"])}
        effA, effB = 100 * float(R["effN_marg"]), 100 * float(R["effN_mixed"])
        print(f"using zj_cross_results.npz ({len(DATA)} joint moments, {int(R['n_events']):,} events)")
    else:
        print("zj_cross_results.npz not found: using the embedded copy of the paper's numbers")
    keys = sorted(DATA)
    x = np.arange(len(keys))
    pull = lambda i: np.array([abs(DATA[k][i] - DATA[k][0]) / DATA[k][1] for k in keys])
    # JHEP print size: set at 0.75\textwidth; legend and tick labels at the
    # pubstyle default sizes, nothing hard-coded smaller.
    fig, a = plt.subplots(figsize=(8.6, 5.6))
    a.axhspan(1e-3, 1.0, color="0.88", alpha=0.6, zorder=0)
    a.plot(x, pull(2), "s", color=C["prior"], ms=9, label=r"LO+PS prior", zorder=3)
    a.plot(x, pull(3), "o", mfc="white", mec=C["maxent"], mew=2.0, ms=9,
           label=rf"MaxEnt, marginal towers ($N_\mathrm{{eff}}/N={effA:.1f}\%$)", zorder=4)
    a.plot(x, pull(4), "o", color=C["maxent"], ms=9,
           label=rf"MaxEnt, $+16$ joint moments ($N_\mathrm{{eff}}/N={effB:.1f}\%$)", zorder=5)
    a.set_yscale("log")
    # every point on the axes: the smallest joint pull is 0.0035, the largest
    # prior pull 72.9
    a.set_ylim(2e-3, 200)
    a.set_xlim(-0.6, len(keys) - 0.4)
    a.set_xticks(x)
    a.set_xticklabels([rf"$({m},{n})$" for m, n in keys], rotation=60, ha="right",
                      rotation_mode="anchor")
    a.tick_params(axis="x", which="minor", bottom=False, top=False)
    a.set_xlabel(r"joint moment $\langle T_k(p_\mathrm{T}^{j_1})\,T_n(p_\mathrm{T}^{j_2})\rangle$,"
                 r"\ \ index $(k,n)$")
    a.set_ylabel(r"$|\mu-\mu_\mathrm{FO}|/\sigma_\mathrm{FO}$")
    a.legend(loc="lower center", bbox_to_anchor=(0.5, 1.01), ncol=1,
             frameon=False, handletextpad=0.4, labelspacing=0.25)
    a.text(0.985, 0.04, r"within the input's uncertainty",
           transform=a.transAxes, ha="right", va="bottom", color="0.35")
    out = os.path.join(HERE, "fig_zj_cross.pdf")
    fig.savefig(out); fig.savefig(out.replace(".pdf", ".png"))
    plt.close(fig)
    p = {i: pull(i) for i in (2, 3, 4)}
    print(f"pulls: prior {p[2].min():.2f}-{p[2].max():.2f} (median {np.median(p[2]):.1f});  marginals max {p[3].max():.2f} "
          f"(median {np.median(p[3]):.2f});  +joint max {p[4].max():.2f} (median {np.median(p[4]):.3f}, min {p[4].min():.4f})"
          f";  effN/N {effA:.1f}% -> {effB:.1f}%")
    print("wrote", out)


if __name__ == "__main__":
    main()
